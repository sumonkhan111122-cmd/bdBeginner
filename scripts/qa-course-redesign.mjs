import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const results = [];
for (const viewport of [{width:1440,height:1050},{width:390,height:844}]) {
  const page = await browser.newPage({viewport});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => sessionStorage.setItem('ai_motion_discount_status', 'dismissed'));
  await page.goto('http://localhost:5173/course/ai-motion', {waitUntil:'networkidle'});
  await page.screenshot({path:`design-assets/course-redesign-${viewport.width}.png`,fullPage:true});
  const overflow = await page.evaluate(() => ({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
  await page.getByRole('button', {name:'Watch the free AI Motion Masterclass preview'}).click();
  await page.locator('#course-demo-dialog').waitFor();
  const modal = await page.locator('#course-demo-dialog').isVisible();
  await page.keyboard.press('Escape');
  const modalClosed = await page.locator('#course-demo-dialog').count() === 0;
  const moduleToggle = page.locator('.academy-module-toggle');
  await moduleToggle.click();
  const collapsed = await moduleToggle.getAttribute('aria-expanded') === 'false';
  await moduleToggle.click();
  const lessonCount = await page.locator('.academy-lesson').count();
  await page.goto('http://localhost:5173/course/ai-motion/learn', {waitUntil:'networkidle'});
  await page.locator('.academy-access-card').waitFor();
  await page.screenshot({path:`design-assets/course-access-${viewport.width}.png`,fullPage:true});
  results.push({viewport:viewport.width,overflow,modal,modalClosed,collapsed,lessonCount,locked:await page.locator('.academy-access-card a[href="/course/ai-motion"]').count(),errors});
  await page.close();
}
const offerPage = await browser.newPage({viewport:{width:1440,height:1000}});
await offerPage.goto('http://localhost:5173/course/ai-motion', {waitUntil:'networkidle'});
await offerPage.locator('.academy-offer-dialog').waitFor({timeout:18000});
await offerPage.screenshot({path:'design-assets/course-offer-desktop.png'});
const offerVisible = await offerPage.locator('.academy-offer-dialog').isVisible();
await offerPage.keyboard.press('Escape');
const offerClosed = await offerPage.locator('.academy-offer-dialog').count() === 0;
await offerPage.locator('.academy-hero-actions .academy-btn-primary').click();
await offerPage.waitForURL('**/checkout');
results.push({offerVisible,offerClosed,checkoutNavigation:offerPage.url().endsWith('/checkout')});
console.log(JSON.stringify(results,null,2));
