await couponPage.goto('http://localhost:5173/course/ai-motion', {waitUntil:'networkidle'});
await couponPage.locator('.academy-offer-dialog').waitFor({timeout:18000});
await couponPage.locator('.academy-offer-dialog .academy-btn-primary').click();
await couponPage.waitForURL('**/checkout');
console.log(JSON.stringify({couponClaimNavigation:couponPage.url().endsWith('/checkout'),claimed:await couponPage.evaluate(() => sessionStorage.getItem('ai_motion_discount_status'))}));
await browser.close();